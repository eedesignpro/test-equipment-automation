# A SCPI command leaked into a public summary line. A bare colon is NOT the
# test: ordinary prose ("Constant-current load: sink amps") and Sphinx roles
# (:class:`Range`) both contain one, and flagging those pushes an author to
# contort readable English instead of removing a command name. Roles are
# stripped first, then three real command shapes are matched.
SPHINX_ROLE_RE = re.compile(r":(?:class|meth|func|data|attr|mod|obj|ref|exc):`[^`]*`")
SCPI_IN_SUMMARY_RE = re.compile(
    r"\*[A-Za-z]{2,4}\??"  # common command: *RST, *IDN?, *CLS
    r"|[A-Za-z]{2,}(?::[A-Za-z0-9<>\[\]|_]+\??)+"  # chained: SOUR:INP:STAT, VOLT:PROT?
    r"|:[A-Za-z]{3,}\??(?=[)\s.,;]|$)"  # lone leading-colon mnemonic: (:TRIG)
)


# Parentheticals that are units or ordinary prose, never a SCPI command. Without
# this the audit flags "(Hz)" in "the frequencies (Hz) of the active peak
# markers", "(Kelvin)" and "(True)" - all of which are the docstring doing its
# job. Mirrors the same guard in tools/strip_scpi_docstrings.py.
NOT_SCPI = {
    "HZ",
    "KHZ",
    "MHZ",
    "GHZ",
    "V",
    "MV",
    "UV",
    "A",
    "MA",
    "UA",
    "W",
    "MW",
    "S",
    "MS",
    "US",
    "NS",
    "PS",
    "OHM",
    "OHMS",
    "DB",
    "DBM",
    "AH",
    "WH",
    "VPP",
    "VRMS",
    "PERCENT",
    "DEG",
    "TRUE",
    "FALSE",
}


def names_scpi(line: str) -> str | None:
    """Return the SCPI command a summary names, or None when it names none."""
    match = SCPI_IN_SUMMARY_RE.search(SPHINX_ROLE_RE.sub("", line))
    if not match:
        return None
    found = match.group(0)
    head = found.strip("() ").split()[0] if found.strip("() ") else ""
    if head.upper() in NOT_SCPI:
        return None
    # A single capital followed by lowercase is an English word, not a SCPI
    # short-form marker: Kelvin is prose where TRACk and NTSc are commands.
    if ":" not in head and re.fullmatch(r"[A-Z][a-z]+", head):
        return None
    return found


gaps: list[str] = []


def summary(func, path: str) -> str:
    """First docstring line, audited against the contract."""
    doc = inspect.getdoc(func)
    if not doc:
        gaps.append(f"{path}: no docstring")
        return ""
    line = doc.strip().splitlines()[0].strip()
    if len(line) > MAX_SUMMARY:
        gaps.append(f"{path}: summary is {len(line)} chars, limit {MAX_SUMMARY}")
    # A SCPI command in a public summary pulls the reader back to the command
    # tree. Private one-to-one setters are allowed to name theirs.
    head = path.rsplit(".", 1)[-1]
    if not head.startswith("_"):
        found = names_scpi(line)
        if found:
            gaps.append(f"{path}: summary names SCPI ({found!r})")
    return line


def signature(func, path: str) -> str:
    try:
        sig = inspect.signature(func)
    except (ValueError, TypeError):
        return "(...)"
    params = [p for name, p in sig.parameters.items() if name != "self"]
    for p in params:
        if p.annotation is inspect.Parameter.empty and p.kind is not p.VAR_KEYWORD:
            gaps.append(f"{path}: parameter {p.name!r} has no annotation")
    if sig.return_annotation is inspect.Signature.empty:
        gaps.append(f"{path}: no return annotation")
    rendered = str(sig).replace("(self, ", "(").replace("(self)", "()")
    return rendered


def public_methods(obj) -> list[tuple[str, object]]:
    """Methods this class defines, excluding inherited base-class plumbing.

    `Node` and `Instrument` contribute eleven raw I/O helpers plus lifecycle
    methods to every node. Listing them per node inflated the first generated
    map to 4193 entries and 119k tokens. They are documented once, in the
    header, not once per node.
    """
    own: dict[str, object] = {}
    for klass in reversed(type(obj).__mro__):
        if klass in (object, Node) or klass.__name__ == "Instrument":
            continue
        for name, value in vars(klass).items():
            if name.startswith("_") or isinstance(value, type):
                continue
            if callable(value) or isinstance(value, (property, staticmethod, classmethod)):
                own[name] = value
    out = []
    for name in sorted(own):
        try:
            attr = getattr(obj, name)
        except Exception:  # noqa: BLE001 - a property may need a live link
            continue
        if callable(attr):
            out.append((name, attr))
    return out


def child_nodes(obj) -> list[tuple[str, Node]]:
    out = []
    for name in sorted(vars(obj)):
        if name.startswith("_"):
            continue
        attr = getattr(obj, name, None)
        if isinstance(attr, Node):
            out.append((name, attr))
    return out


def collect(handle: str, node, out: list[tuple[str, object]], depth: int = 0) -> None:
    out.append((handle, node))
    if depth < 2:
        for child_name, child in child_nodes(node):
            collect(f"{handle}.{child_name}", child, out, depth + 1)


CHANNEL_HANDLE_RE = re.compile(r".*\.ch\d+$")


def channel_gate(module) -> str | None:
    """One line naming how many channel nodes each model of the family gets.

    Read from the driver's ``_MODEL_INFO`` table, so the gate cannot drift from
    the code that applies it (design standard 9.1 rule 4). Returns None when the
    driver has no such table, in which case the map simply omits the line.
    """
    table = getattr(module, "_MODEL_INFO", None)
    if not isinstance(table, dict):
        # A driver that reads its channel count from the hardware has no model
        # table to print. It states the gate in a module-level string instead.
        stated = getattr(module, "CHANNEL_GATE", None)
        return stated if isinstance(stated, str) and stated else None
    by_count: dict[int, list[str]] = {}
    for model, info in table.items():
        if not isinstance(info, dict):
            continue
        count = info.get("channels", info.get("outputs"))
        if isinstance(count, int):
            by_count.setdefault(count, []).append(str(model))
    if not by_count:
        return None
    parts = [f"{n} on {', '.join(sorted(models))}" for n, models in sorted(by_count.items())]
    return (
        "Channel nodes are the same shape on every model, so they are listed once. "
        f"Channels per model: {'; '.join(parts)}."
    )


def collapse_handles(handles: list[str]) -> str:
    """Render ch1..ch8 as a range instead of eight separate headings."""
    if len(handles) == 1:
        return handles[0]
    if len(handles) > 2:
        return f"{handles[0]} .. {handles[-1]}"
    return " , ".join(handles)


def emit_driver(lines: list[str], root_handle: str, inst, gate: str | None = None) -> int:
    """Emit one section per distinct node type, not per node instance.

    Eight channels share one `_Channel` class. Listing it eight times inflated
    the map from 1362 real methods to 2585 entries.
    """
    found: list[tuple[str, object]] = []
    collect(root_handle, inst, found)

    groups: dict[tuple, list[str]] = {}
    reps: dict[tuple, object] = {}
    for handle, node in found:
        methods = public_methods(node)
        if not methods:
            continue
        key = (type(node).__name__, tuple(n for n, _ in methods))
        groups.setdefault(key, []).append(handle)
        reps.setdefault(key, node)

    count = 0
    for key, handles in groups.items():
        node = reps[key]
        label = collapse_handles(handles)
        suffix = f"  ({len(handles)} instances)" if len(handles) > 1 else ""
        lines.append(f"\n### {label}  ({type(node).__name__}){suffix}\n")
        if gate and any(CHANNEL_HANDLE_RE.match(h) for h in handles):
            lines.append(f"{gate}\n")
        lines.append("```")
        for name, func in public_methods(node):
            path = f"{handles[0]}.{name}"
            lines.append(f"{name}{signature(func, path)}".ljust(70) + f"  {summary(func, path)}")
        lines.append("```")
        count += len(key[1])
    return count


def build_one(label: str, module_name: str, class_name: str, arg) -> tuple[str, int]:
    """Build the map for one instrument. Returns the file text and method count."""
    lines = [f"# {label}  (`{class_name}`)", "", _RULES]
    try:
        module = __import__(module_name, fromlist=[class_name])
        cls = getattr(module, class_name)
        inst = cls() if arg is None else cls(arg)
    except Exception as exc:  # noqa: BLE001 - report and continue
        lines.append(f"\n> generator could not instantiate: {exc}")
        return "\n".join(lines) + "\n", 0
    count = emit_driver(lines, class_name.lower(), inst, channel_gate(module))
    return "\n".join(lines) + "\n", count


def build_all() -> tuple[dict[Path, str], list[tuple[str, str, int, int]]]:
    """Build every per-instrument file plus the index. Returns paths and stats."""
    files: dict[Path, str] = {}
    stats: list[tuple[str, str, int, int]] = []

    for label, module_name, class_name, arg in DRIVERS:
        slug = module_name.rsplit(".", 1)[-1]
        text, count = build_one(label, module_name, class_name, arg)
        files[OUT_DIR / f"{slug}.md"] = text
        stats.append((label, slug, count, len(text)))

    index = [
        "# Driver API map",
        "",
        "Generated by `tools/gen_api_map.py`. Do not edit by hand.",
        "",
        "**Read only the file for the instrument you are using.** One file per",
        "instrument, so a script that drives the scope pays nothing for the DMM.",
        "",
        "| Instrument | File | Methods | Approx tokens |",
        "|---|---|---|---|",
    ]
    for label, slug, count, size in stats:
        index.append(
            f"| {label} | [`api-map/{slug}.md`](api-map/{slug}.md) | {count} | {size // 4} |"
        )

    total_methods = sum(c for _, _, c, _ in stats)
    total_size = sum(s for _, _, _, s in stats)
    index += [
        f"| **all {len(stats)}** | | **{total_methods}** | **{total_size // 4}** |",
        "",
        "Naming rules and the reasoning behind them are in",
        "[`driver-api-design.md`](driver-api-design.md).",
    ]
    files[INDEX_PATH] = "\n".join(index) + "\n"
    return files, stats


def main() -> int:
    files, stats = build_all()
    failed = [slug for _, slug, count, _ in stats if count == 0]
    if failed:
        print(f"generator could not instantiate: {', '.join(failed)}")
        return 1
    check = "--check" in sys.argv[1:]

    if check:
        stale = [
            path
            for path, text in files.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)}")
            print("Run tools/gen_api_map.py.")
            return 1
        print(f"api map is current ({sum(c for _, _, c, _ in stats)} methods).")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")

    print(f"wrote {len(files)} files under docs/")
    for label, slug, count, size in sorted(stats, key=lambda s: -s[3]):
        print(f"  {size // 4:7d} tok  {count:5d} methods  api-map/{slug}.md  ({label})")
    biggest = max(s[3] for s in stats) // 4
    total = sum(s[3] for s in stats) // 4
    print(f"\nlargest single instrument: {biggest} tokens")
    print(f"all {len(stats)} combined:            {total} tokens")

    print(f"\ncontract gaps: {len(gaps)}")
    by_kind: dict[str, int] = {}
    for gap in gaps:
        kind = gap.split(": ", 1)[1].split(" (")[0]
        kind = "summary too long" if "chars, limit" in kind else kind
        by_kind[kind] = by_kind.get(kind, 0) + 1
    for kind, n in sorted(by_kind.items(), key=lambda kv: -kv[1]):
        print(f"  {n:5d}  {kind}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
