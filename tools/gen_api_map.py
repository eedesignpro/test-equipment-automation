"""Generate docs/api-map.md from the driver source. Also report contract gaps.

An agent that drafts a test cannot autocomplete. It pays context tokens to
read. Eight driver files hold about 8700 lines, so a full read is wasteful.
This writes one compact file: one line per public method, with the call path,
the signature, the return type, and one short purpose clause.

The generator touches no hardware. Every driver builds its node tree in
``__init__`` with no I/O, so the tree can be walked from an unconnected
instance. A driver whose channel count depends on the model builds only its
first channel there and attaches the rest in ``connect()``; the map documents
that one channel as the generic pattern and prints the per-model channel count
from the driver's ``_MODEL_INFO`` table.

Run:  .venv/Scripts/python.exe tools/gen_api_map.py
      .venv/Scripts/python.exe tools/gen_api_map.py --check

``--check`` writes nothing. It exits non-zero when the map is stale, so the
test suite can fail on a map that no longer matches the code.

Contract rules audited (docs/driver-api-design.md section 9.1):
  1. every public method has a docstring
  2. the first docstring line is one sentence under 90 characters
  3. the first line names no SCPI command
  4. every parameter and the return carry an annotation
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from common.node import Node  # noqa: E402

INDEX_PATH = ROOT / "docs" / "api-map.md"
OUT_DIR = ROOT / "docs" / "api-map"
MAX_SUMMARY = 90

# Shared header on every per-instrument file. An agent reads one instrument's
# file, so the naming rules have to appear in each one.
_RULES = """Generated by `tools/gen_api_map.py`. Do not edit by hand.

One line per public method: signature, return type, and purpose. Read this
instead of the driver source.

`set_` changes state and returns the read-back. `get_` reads a setting or a
status. `meas_` takes a new measurement. `cmd_` sends a transient command.
Names are paths, so the general segment comes first. Rules and rationale are in
`docs/driver-api-design.md`.

Every node also inherits `connect`, `disconnect`, `snapshot`, `restore`,
`preserved_setup` and raw I/O helpers from the base classes. Those are listed
once here rather than on every node."""

